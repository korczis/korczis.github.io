#!/usr/bin/env node
// Writes the site's translations from i18n/strings.toml (one table per key, one value per language)
// into zola.toml, between generated markers: [translations] for the default language and
// [languages.<code>.translations] for every other. Zola's trans() reads them at build time.
//
// usage: node scripts/build-i18n.mjs           rewrite the generated block of zola.toml
//        node scripts/build-i18n.mjs --check   exit 1 if it is stale or a key misses a language
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG = join(ROOT, 'zola.toml');
const BEGIN = '# >>> generated by scripts/build-i18n.mjs from i18n/strings.toml; do not edit >>>';
const END = '# <<< generated translations <<<';
const strings = parse(readFileSync(join(ROOT, 'i18n/strings.toml'), 'utf8'));
const config = readFileSync(CONFIG, 'utf8');
const parsed = parse(config.split(BEGIN)[0]);
const languages = [parsed.default_language, ...Object.keys(parsed.languages ?? {})];
const q = (s) => JSON.stringify(s);

const missing = [];
for (const [key, values] of Object.entries(strings)) {
  for (const code of languages) if (typeof values[code] !== 'string' || !values[code].trim()) missing.push(`${key}.${code}`);
}
const block = [BEGIN];
for (const code of languages) {
  block.push('', code === parsed.default_language ? '[translations]' : `[languages.${code}.translations]`);
  for (const [key, values] of Object.entries(strings)) block.push(`${key} = ${q(values[code] ?? '')}`);
}
block.push(END);
const text = `${config.includes(BEGIN) ? config.slice(0, config.indexOf(BEGIN)).trimEnd() : config.trimEnd()}\n\n${block.join('\n')}\n`;

if (missing.length) {
  for (const m of missing) console.error(`✗ i18n/strings.toml: ${m} is missing`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  if (config !== text) { console.error('zola.toml translations are stale: run npm run i18n'); process.exit(1); }
  console.log(`i18n: ${Object.keys(strings).length} keys in ${languages.join(', ')}, current`);
} else {
  writeFileSync(CONFIG, text);
  console.log(`i18n: ${Object.keys(strings).length} keys written for ${languages.join(', ')}`);
}
