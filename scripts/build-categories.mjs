#!/usr/bin/env node
// Derives one Zola page per category and language, content/projects/<key>[.<lang>].md, from
// [categories.<key>] in data/projects.toml and data/index.json: title, description, SEO and OG front
// matter and the article. The page lists the projects of that category (templates/category.html);
// nothing in these files is written by hand, and their prose is i18n/derive.toml.
//
// usage: node scripts/build-categories.mjs           write them (and remove stale ones)
//        node scripts/build-categories.mjs --check   exit 1 if any is missing, stale or orphaned
import { join } from 'node:path';
import { ROOT, identity, languages, local, ogPrefix, q, readJson, readToml, suffix, t, writeOrCheck } from './lib/derive.mjs';
import { listing, loadGlossary, nameLink, termLink, termsForCategory, termsForNames, tl } from './lib/terms.mjs';
import { vizBlock } from './lib/viz.mjs';

const DIR = join(ROOT, 'content/projects');
const MARK = '# generated by scripts/build-categories.mjs from data/projects.toml; do not edit';
const catalogue = readToml('data/projects.toml');
const index = readJson('data/index.json');
const glossary = loadGlossary(ROOT);
const me = identity();

// Every primary language of the category's original repositories (data/index.json), the most
// common first, never the rule list that classified them. The article names the first four; the
// page's terms build on all of them.
function categoryLanguages(key) {
  const counts = new Map();
  for (const r of index.repos) if (r.category === key && r.language) counts.set(r.language, (counts.get(r.language) ?? 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([name]) => name);
}

// The article of a category page, derived: what the category holds, how many repositories, the
// languages it is measured to be written in, the featured projects, and how the classification works.
function article(key, c, lang) {
  const n = index.by_category[key] ?? 0;
  const langs = categoryLanguages(key).slice(0, 4).map((name) => nameLink(glossary, name, lang));
  const featured = catalogue.projects.filter((p) => p.category === key).map((p) => `**${p.name}**`);
  const concepts = (glossary.byCategory.get(key) ?? []).map((id) => termLink(glossary, id, lang));
  const p = [local(c, 'description', lang)];
  p.push(t('derive_category_holds', lang, {
    n,
    languages: langs.length ? t('derive_category_languages', lang, { list: listing(langs, lang) }) : '',
    featured: featured.length ? t('derive_category_featured', lang, { list: listing(featured, lang) }) : '',
  }));
  if (concepts.length) p.push(t('derive_category_concept', lang, { list: listing(concepts, lang) }));
  p.push(tl(glossary, 'derive_category_how', lang));
  return p.join('\n\n');
}

// The newest moment as UTC to the second (GitLab writes offsets and milliseconds), else the fallback.
const utc = (ms, fallback) => new Date(Number.isFinite(ms) ? ms : fallback).toISOString().replace(/\.\d+Z$/, 'Z');

const wanted = new Map();
for (const [position, [key, c]] of Object.entries(catalogue.categories).entries()) {
  const projects = catalogue.projects.filter((p) => p.category === key);
  const n = index.by_category[key] ?? 0;
  const names = [...projects.map((p) => p.name), ...index.repos.filter((r) => r.category === key && !r.curated).slice(0, 6).map((r) => r.name)];
  for (const lang of languages()) {
    const name = local(c, 'name', lang);
    wanted.set(`${key}${suffix(lang)}.md`, `+++
${MARK}
title = ${q(name)}
description = ${q(local(c, 'description', lang))}
template = "category.html"
weight = ${position + 1}
updated = ${q(utc(Math.max(...index.repos.filter((r) => r.category === key).map((r) => Date.parse(r.pushed_at))), index.generated_at))}

[taxonomies]
tags = [${[name, ...names.slice(0, 4)].map(q).join(', ')}]

[extra]
category = ${q(key)}
og_title = ${q(t('derive_category_og', lang, { name, n }))}
og_image = ${q(`og/${ogPrefix(lang)}category-${key}.png`)}
schema = "collection"
terms = [${[...termsForCategory(glossary, key, categoryLanguages(key)), ...termsForNames(glossary, projects.flatMap((p) => p.stack ?? [])), 'repository'].filter((x, i, a) => a.indexOf(x) === i).map(q).join(', ')}]
keywords = [${[name, ...names, me.nameIn(lang)].map(q).join(', ')}]
${vizBlock({ kind: 'constellation', source: 'index.repos', title: 'viz_category_galaxy_title', lead: 'viz_category_galaxy_lead', height: 'lg' })}+++
${article(key, c, lang)}
`);
  }
}

writeOrCheck(wanted, { dir: DIR, mark: MARK, label: 'categories', orphanWhy: 'has no category any more' });
