#!/usr/bin/env node
// Derives one Zola page per category, content/projects/<key>.md, from [categories.<key>] in
// data/projects.toml: title, description, SEO and OG front matter. The page lists the projects of
// that category (templates/category.html); nothing in these files is written by hand.
//
// usage: node scripts/build-categories.mjs           write them (and remove stale ones)
//        node scripts/build-categories.mjs --check   exit 1 if any is missing, stale or orphaned
import { existsSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';
import { listing, loadGlossary, nameLink, termLink, termsForCategory, termsForNames } from './lib/terms.mjs';
import { vizBlock } from './lib/viz.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'content/projects');
const CHECK = process.argv.includes('--check');
const MARK = '# generated by scripts/build-categories.mjs from data/projects.toml; do not edit';
const catalogue = parse(readFileSync(join(ROOT, 'data/projects.toml'), 'utf8'));
const index = JSON.parse(readFileSync(join(ROOT, 'data/index.json'), 'utf8'));
const q = (s) => JSON.stringify(s);
const glossary = loadGlossary(ROOT);

// Czech plural of "repository": 1 repozitář, 2-4 repozitáře, otherwise repozitářů.
const csRepos = (n) => (n === 1 ? 'repozitář' : n >= 2 && n <= 4 ? 'repozitáře' : 'repozitářů');
// The languages a category is measured to be written in: the four most common primary languages
// of its original repositories (data/index.json), never the rule list that classified them.
function topLanguages(key) {
  const counts = new Map();
  for (const r of index.repos) if (r.category === key && r.language) counts.set(r.language, (counts.get(r.language) ?? 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 4).map(([name]) => name);
}

// Every primary language of the category's original repositories, the most common first: the
// terms a category page builds on (its article names only the top four).
function allLanguages(key) {
  const counts = new Map();
  for (const r of index.repos) if (r.category === key && r.language) counts.set(r.language, (counts.get(r.language) ?? 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([name]) => name);
}

// The article of a category page, derived: what the category holds, how many repositories, the
// languages it is measured to be written in, the featured projects, and how the classification works.
function article(key, c, lang) {
  const cs = lang === 'cs';
  const repos = index.by_category[key] ?? 0;
  const langs = topLanguages(key).map((n) => nameLink(glossary, n, lang));
  const featured = catalogue.projects.filter((p) => p.category === key).map((p) => `**${p.name}**`);
  const concepts = (glossary.byCategory.get(key) ?? []).map((id) => termLink(glossary, id, lang));
  const p = [cs ? c.description_cs : c.description];
  p.push(cs
    ? `Kategorie má ${repos} ${csRepos(repos)}${langs.length ? `; nejčastějšími jazyky jsou ${listing(langs, lang)}` : ''}.${featured.length ? ` Vybrané projekty: ${listing(featured, lang)}.` : ''}`
    : `The category holds ${repos} original repositor${repos === 1 ? 'y' : 'ies'}${langs.length ? `, written most often in ${listing(langs, lang)}` : ''}.${featured.length ? ` Featured: ${listing(featured, lang)}.` : ''}`);
  if (concepts.length) p.push(cs ? `Klíčový pojem: ${listing(concepts, lang)}.` : `Key concept: ${listing(concepts, lang)}.`);
  p.push(cs
    ? `*Jak kategorie vznikají:* nikdo je ručně nepřiřazuje. ${termLink(glossary, 'repository', lang)} spadne do kategorie, když jeho název, popis nebo témata odpovídají klíčovým slovům pravidla, jinak rozhodne jeho hlavní jazyk; forky a ${termLink(glossary, 'mirror', lang, 'mirrory')} se nepočítají za vlastní práci.`
    : `*How categories are made:* nobody assigns them by hand. A ${termLink(glossary, 'repository', lang, 'repository')} falls into a category when its name, description or topics match the rule's keywords, otherwise its primary language decides; ${termLink(glossary, 'fork', lang, 'forks')} and ${termLink(glossary, 'mirror', lang, 'mirrors')} never count as the owner's work.`);
  return p.join('\n\n');
}

const wanted = new Map();
for (const [position, [key, c]] of Object.entries(catalogue.categories).entries()) {
  const projects = catalogue.projects.filter((p) => p.category === key);
  const repos = index.by_category[key] ?? 0;
  const names = [...projects.map((p) => p.name), ...index.repos.filter((r) => r.category === key && !r.curated).slice(0, 6).map((r) => r.name)];
  for (const lang of ['en', 'cs']) {
    const cs = lang === 'cs';
    const name = cs ? c.name_cs : c.name;
    const title = cs ? `${name}: ${repos} ${csRepos(repos)}.` : `${name}: ${repos} repositor${repos === 1 ? 'y' : 'ies'}.`;
    wanted.set(cs ? `${key}.cs.md` : `${key}.md`, `+++
${MARK}
title = ${q(name)}
description = ${q(cs ? c.description_cs : c.description)}
template = "category.html"
weight = ${position + 1}

[taxonomies]
tags = [${[name, ...names.slice(0, 4)].map(q).join(', ')}]

[extra]
category = ${q(key)}
og_title = ${q(title)}
og_image = ${q(`og/${cs ? 'cs-' : ''}category-${key}.png`)}
schema = "collection"
terms = [${[...termsForCategory(glossary, key, allLanguages(key)), ...termsForNames(glossary, projects.flatMap((p) => p.stack ?? [])), 'repository'].filter((t, i, a) => a.indexOf(t) === i).map(q).join(', ')}]
keywords = [${[name, ...names, cs ? 'Tomáš Korčák' : 'Tomas Korcak'].map(q).join(', ')}]
${vizBlock({ kind: 'constellation', source: 'index.repos', title: 'viz_category_galaxy_title', lead: 'viz_category_galaxy_lead', height: 'lg' })}+++
${article(key, c, lang)}
`);
  }
}

const findings = [];
for (const [name, text] of wanted) {
  const path = join(DIR, name);
  if (CHECK) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) findings.push(`content/projects/${name} is missing or stale`);
  } else {
    writeFileSync(path, text);
  }
}
for (const name of readdirSync(DIR)) {
  if (name.startsWith('_index') || wanted.has(name)) continue;
  if (!readFileSync(join(DIR, name), 'utf8').includes(MARK)) continue;
  if (CHECK) findings.push(`content/projects/${name} has no category any more`);
  else unlinkSync(join(DIR, name));
}

if (CHECK && findings.length) {
  for (const f of findings) console.error(`✗ ${f}; run node scripts/build-categories.mjs`);
  process.exit(1);
}
console.log(`categories: ${wanted.size} pages ${CHECK ? 'current' : 'written'}`);
