#!/usr/bin/env node
// Derives the services and the skills: content/services/ (one page per service of data/services.toml
// and the section) and content/skills/ (one page per capability of data/experience-rules.toml and the
// section), in every language, and data/services.json, the evidence their templates and graphs read
// (scripts/lib/services.mjs). The words of a service are the owner's; everything else on these pages
// is derived: the skills it draws on, the public repositories that show them, the client use cases
// (sector and role, never a name, date or number), the languages and technologies, the articles.
//
// usage: node scripts/build-services.mjs           write them (and remove stale ones)
//        node scripts/build-services.mjs --check   exit 1 if any is missing, stale or orphaned
import { join } from 'node:path';
import { ROOT, clip, identity, languages, limits, local, ogPrefix, q, readToml, suffix, t, writeOrCheck } from './lib/derive.mjs';
import { listing, loadGlossary, mdEscape, termLink, tl } from './lib/terms.mjs';
import { loadSources } from './lib/skills.mjs';
import { loadServices, serviceEvidence } from './lib/services.mjs';
import { vizBlock } from './lib/viz.mjs';
import { cliArgs } from './lib/cli.mjs';

cliArgs({ '--check': true }, { derived: true });

const MARK_SERVICES = '# generated by scripts/build-services.mjs from data/services.toml; do not edit';
const MARK_SKILLS = '# generated by scripts/build-services.mjs from data/experience-rules.toml; do not edit';
const g = loadGlossary(ROOT);
const me = identity();
const sources = loadSources();
const services = loadServices();
const rules = readToml('data/experience-rules.toml');
const ev = serviceEvidence(g, sources, services);
const LANGS = languages();
const LIMITS = limits();
// A description within the schema's limits (the full text stays on the page), padded when short.
const describe = (text, lang) => clip(text, LIMITS.description.max, { min: LIMITS.description.min, pad: t('derive_service_pad', lang, { author: me.nameIn(lang) }) });

const capName = (key, lang) => local(rules.capabilities[key], 'name', lang) ?? key;
const sectorName = (key, lang) => local(rules.sectors?.[key], 'name', lang) ?? null;
const roleName = (key, lang) => local(rules.roles[key], 'name', lang) ?? key;
const skillLink = (key, lang) => `[${capName(key, lang)}](@/skills/${key}${suffix(lang)}.md)`;
const serviceLink = (s, lang) => `[${local(s, 'name', lang)}](@/services/${s.id}${suffix(lang)}.md)`;
const techLinks = (list, lang, n = 8) => list.slice(0, n).map((x) => termLink(g, x.id, lang));
const uniq = (xs) => [...new Set(xs.filter(Boolean))];
const domainOf = (key) => rules.capabilities[key]?.domain;

// The terms a page builds on: its skills' concepts, its technologies, and the two this section adds.
const termsOf = (skills, technologies) => uniq([
  ...skills.map((k) => rules.capabilities[k]?.term).filter((id) => g.byId.has(id)),
  ...technologies.slice(0, 10).map((x) => x.id),
]);

function serviceArticle(s, lang) {
  const e = ev.services[s.id];
  const p = [local(s, 'problem', lang), local(s, 'principle', lang)];
  p.push(t('derive_service_skills', lang, { list: listing(e.skills.map((k) => skillLink(k, lang)), lang) }));
  if (e.stack.length) p.push(t('derive_service_stack', lang, { list: listing(e.stack.map((x) => termLink(g, x.id, lang)), lang) }));
  const tech = techLinks(e.technologies, lang);
  if (tech.length) p.push(t('derive_service_tech', lang, { list: listing(tech, lang) }));
  const work = e.repos.filter((r) => r.how === 'words').length;
  if (e.repos.length) p.push(t('derive_service_repos', lang, { n: e.repos.length, words: work }));
  if (e.engagements.length) {
    const sectors = uniq(e.engagements.map((x) => sectorName(x.sector, lang)));
    const roles = uniq(e.engagements.flatMap((x) => x.roles).map((k) => roleName(k, lang)));
    p.push(t('derive_service_clients', lang, { sectors: listing(sectors, lang) || t('derive_service_sector_any', lang), roles: listing(roles, lang) }));
  }
  p.push(tl(g, 'derive_service_how', lang));
  return p.join('\n\n');
}

function skillArticle(key, lang) {
  const c = rules.capabilities[key];
  const e = ev.skills[key];
  const p = [local(c, 'description', lang)];
  if (c.term && g.byId.has(c.term)) p.push(t('derive_skill_term', lang, { term: termLink(g, c.term, lang) }));
  const used = services.services.filter((s) => e.services.includes(s.id));
  if (used.length) p.push(t('derive_skill_services', lang, { list: listing(used.map((s) => serviceLink(s, lang)), lang) }));
  const tech = techLinks(e.technologies, lang);
  if (tech.length) p.push(t('derive_skill_tech', lang, { list: listing(tech, lang) }));
  const words = e.repos.filter((r) => r.how === 'words');
  if (words.length) p.push(t('derive_skill_public_words', lang, { list: listing(words.slice(0, 4).map((r) => `[${mdEscape(r.name)}](${r.url})`), lang) }));
  else if (e.repos.length) p.push(t('derive_skill_public_field', lang, { n: e.repos.length }));
  if (e.engagements.length) {
    const sectors = uniq(e.engagements.map((x) => sectorName(x.sector, lang)));
    p.push(t('derive_skill_clients_cases', lang, { sectors: listing(sectors, lang) || t('derive_service_sector_any', lang) }));
  }
  p.push(tl(g, 'derive_skill_page_how', lang));
  return p.join('\n\n');
}

const files = { services: new Map(), skills: new Map() };
const graph = (title, lead) => vizBlock({ kind: 'graph', source: 'services.graph', title, lead, height: 'lg' });

for (const lang of LANGS) {
  const sfx = suffix(lang);
  const n = services.services.length;
  const skillKeys = Object.keys(rules.capabilities);
  const allTech = new Map();
  for (const s of services.services) for (const x of ev.services[s.id].technologies) allTech.set(x.id, (allTech.get(x.id) ?? 0) + x.n);
  const topTech = [...allTech].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([id, k]) => ({ id, n: k }));
  files.services.set(`_index${sfx}.md`, `+++
${MARK_SERVICES}
title = ${q(t('services_title', lang))}
description = ${q(t('services_lead', lang, { n }))}
template = "services.html"
page_template = "service.html"
sort_by = "weight"

[extra]
og_title = ${q(t('services_og', lang, { n }))}
og_image = ${q(`og/${ogPrefix(lang)}services.png`)}
schema = "collection"
terms = [${uniq(['service', 'skill', ...termsOf(skillKeys, topTech)]).map(q).join(', ')}]
keywords = [${[t('services_title', lang), ...services.services.map((s) => local(s, 'name', lang)), me.nameIn(lang)].map(q).join(', ')}]
${graph('viz_services_graph_title', 'viz_services_graph_lead')}+++
${[t('derive_services_intro', lang, { n, list: listing(services.services.map((s) => serviceLink(s, lang)), lang) }), tl(g, 'derive_services_how', lang)].join('\n\n')}
`);
  services.services.forEach((s, i) => {
    const e = ev.services[s.id];
    files.services.set(`${s.id}${sfx}.md`, `+++
${MARK_SERVICES}
title = ${q(local(s, 'name', lang))}
description = ${q(describe(local(s, 'promise', lang), lang))}
template = "service.html"
weight = ${i + 1}

[taxonomies]
tags = [${[t('services_title', lang), ...e.skills.slice(0, 3).map((k) => capName(k, lang))].map(q).join(', ')}]

[extra]
service = ${q(s.id)}
icon = ${q(s.icon)}
og_title = ${q(local(s, 'name', lang))}
og_image = ${q(`og/${ogPrefix(lang)}service-${s.id}.png`)}
schema = "service"
terms = [${uniq(['service', ...e.stack.map((x) => x.id), ...termsOf(e.skills, e.technologies)]).map(q).join(', ')}]
keywords = [${[local(s, 'name', lang), ...e.skills.map((k) => capName(k, lang)), me.nameIn(lang)].map(q).join(', ')}]
${graph('viz_service_graph_title', 'viz_service_graph_lead')}+++
${serviceArticle(s, lang)}
`);
  });

  files.skills.set(`_index${sfx}.md`, `+++
${MARK_SKILLS}
title = ${q(t('services_skills_title', lang))}
description = ${q(t('services_skills_lead', lang, { n: skillKeys.length }))}
template = "skills.html"
page_template = "skill.html"
sort_by = "weight"

[extra]
og_title = ${q(t('skills_og', lang, { n: skillKeys.length }))}
og_image = ${q(`og/${ogPrefix(lang)}skills.png`)}
schema = "collection"
terms = [${uniq(['skill', 'service', ...termsOf(skillKeys, topTech)]).map(q).join(', ')}]
keywords = [${[t('services_skills_title', lang), ...skillKeys.slice(0, 12).map((k) => capName(k, lang)), me.nameIn(lang)].map(q).join(', ')}]
${graph('viz_services_graph_title', 'viz_services_graph_lead')}+++
${[t('derive_skills_intro', lang, { n: skillKeys.length, services: n }), tl(g, 'derive_skills_how', lang)].join('\n\n')}
`);
  // Skills in the order of the domains, then by how many services draw on them.
  const order = rules.domain_order ?? [];
  const sorted = [...skillKeys].sort((a, b) => order.indexOf(domainOf(a)) - order.indexOf(domainOf(b))
    || ev.skills[b].services.length - ev.skills[a].services.length || a.localeCompare(b));
  sorted.forEach((key, i) => {
    const e = ev.skills[key];
    files.skills.set(`${key}${sfx}.md`, `+++
${MARK_SKILLS}
title = ${q(capName(key, lang))}
description = ${q(describe(local(rules.capabilities[key], 'description', lang), lang))}
template = "skill.html"
weight = ${i + 1}

[taxonomies]
tags = [${[t('services_skills_title', lang), local(rules.domains[domainOf(key)], 'name', lang)].filter(Boolean).map(q).join(', ')}]

[extra]
skill = ${q(key)}
og_title = ${q(`${capName(key, lang)}: ${t('services_skills_title', lang).toLowerCase()}`)}
og_image = ${q(`og/${ogPrefix(lang)}skill-${key}.png`)}
schema = "skill"
terms = [${uniq(['skill', ...termsOf([key], e.technologies)]).map(q).join(', ')}]
keywords = [${[capName(key, lang), ...e.services.map((id) => local(services.services.find((s) => s.id === id), 'name', lang)), me.nameIn(lang)].map(q).join(', ')}]
${graph('viz_skill_page_graph_title', 'viz_skill_page_graph_lead')}+++
${skillArticle(key, lang)}
`);
  });
}

const json = `${JSON.stringify({ schema: 'korczis-hub-services/v1', generated_from: ['data/services.toml', 'data/experience-rules.toml', 'data/experience.json', 'data/index.json', 'data/recent.json', 'data/projects.toml'], ...ev }, null, 2)}\n`;
writeOrCheck(files.services, { dir: join(ROOT, 'content/services'), mark: MARK_SERVICES, label: 'services', orphanWhy: 'has no service any more' });
writeOrCheck(files.skills, { dir: join(ROOT, 'content/skills'), mark: MARK_SKILLS, label: 'skills', orphanWhy: 'has no capability any more' });
writeOrCheck(new Map([['services.json', json]]), { dir: join(ROOT, 'data'), mark: null, label: 'services.json' });
