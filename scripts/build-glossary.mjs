#!/usr/bin/env node
// Derives the glossary, content/glossary/, from data/glossary.toml: one page per term and language
// and the section page. Where a term is used and which terms are related are derived from the
// front matter of every other page (extra.terms): a page that names a term links to it, and the
// term's page links back. Nothing in these files is written by hand.
//
// usage: node scripts/build-glossary.mjs           write them (and remove stale ones)
//        node scripts/build-glossary.mjs --check   exit 1 if any is missing, stale or orphaned
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';
import { loadGlossary, termLink } from './lib/terms.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'content');
const DIR = join(CONTENT, 'glossary');
const CHECK = process.argv.includes('--check');
const MARK = '# generated by scripts/build-glossary.mjs from data/glossary.toml; do not edit';
const q = (s) => JSON.stringify(s);
const g = loadGlossary(ROOT);
const strings = parse(readFileSync(join(ROOT, 'i18n/strings.toml'), 'utf8'));
const tr = (key, lang) => strings[key][lang];

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const path = join(dir, e.name);
    return e.isDirectory() ? walk(path) : e.name.endsWith('.md') ? [path] : [];
  });
}

// Every page outside the glossary that names terms: its Zola path (as get_page takes it) by language.
const usage = new Map(g.terms.map((t) => [t.id, { en: [], cs: [] }]));
const together = new Map(g.terms.map((t) => [t.id, new Map()]));
for (const file of walk(CONTENT).sort()) {
  if (file.startsWith(DIR)) continue;
  const match = readFileSync(file, 'utf8').match(/^\+\+\+\n([\s\S]*?)\n\+\+\+/);
  const terms = match ? parse(match[1]).extra?.terms ?? [] : [];
  const path = relative(CONTENT, file);
  const lang = path.endsWith('.cs.md') ? 'cs' : 'en';
  for (const id of terms) {
    if (!usage.has(id)) continue; // check-glossary reports unknown ids
    usage.get(id)[lang].push(path);
    if (lang === 'en') for (const other of terms) if (other !== id && usage.has(other)) together.get(id).set(other, (together.get(id).get(other) ?? 0) + 1);
  }
}

const clip = (text) => (text.length > 165 ? `${text.slice(0, 162).replace(/\s+\S*$/, '')}…` : text.length < 50 ? `${text} ${'A term of the glossary.'}` : text);
const KINDS = ['language', 'technology', 'concept'];
const sorted = [...g.terms].sort((a, b) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || a.term.localeCompare(b.term));

const wanted = new Map();
for (const lang of ['en', 'cs']) {
  const cs = lang === 'cs';
  const sfx = cs ? '.cs' : '';
  wanted.set(`_index${sfx}.md`, `+++
${MARK}
title = ${q(tr('glossary', lang))}
description = ${q(tr('glossary_lead', lang).replace('{n}', g.terms.length))}
template = "glossary.html"
page_template = "term.html"
sort_by = "weight"

[extra]
og_title = ${q(tr('glossary_og', lang).replace('{n}', g.terms.length))}
og_image = ${q(`og/${cs ? 'cs-' : ''}glossary.png`)}
schema = "glossary"
terms = ["open-source", "repository", "front-matter", "static-site-generator"]
keywords = [${[tr('glossary', lang), ...sorted.filter((t) => t.term.length > 1).slice(0, 10).map((t) => t.term), cs ? 'Tomáš Korčák' : 'Tomas Korcak'].map(q).join(', ')}]
+++
${cs
    ? `Slovník je společný jazyk celého webu. Každá stránka ve svém ${termLink(g, 'front-matter', lang)} jmenuje pojmy, na kterých stojí, a končí jejich výkladem; stránka pojmu naopak ukazuje všechny stránky, které ho používají, a pojmy, které se objevují s ním. Vazby se odvozují, nikdo je nepíše ručně.\n\nKaždá definice je krátká a srozumitelná a odkazuje na zdroj, kde se dá číst dál: dokumentaci, specifikaci nebo encyklopedii. Pojmy jsou tří druhů: programovací jazyky, technologie a koncepty.`
    : `The glossary is the shared language of the whole site. Every page names the terms it builds on in its ${termLink(g, 'front-matter', lang, 'front matter')} and ends by explaining them; a term's page in turn shows every page that uses it and the terms that appear alongside. These links are derived, never typed by hand.\n\nEach definition is short, in plain words, and points to a source to read further: documentation, a specification or an encyclopedia. Terms come in three kinds: programming languages, technologies and concepts.`}
`);
  sorted.forEach((t, position) => {
    const name = (cs && t.term_cs) || t.term;
    const definition = cs ? t.definition_cs : t.definition;
    const related = [...together.get(t.id)].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 8).map(([id]) => id);
    const title = (cs ? t.title_cs : t.title) ?? name;
    wanted.set(`${t.id}${sfx}.md`, `+++
${MARK}
title = ${q(title)}
description = ${q(clip(definition))}
template = "term.html"
weight = ${position + 1}

[taxonomies]
tags = [${[tr('glossary', lang), tr(`kind_term_${t.kind}`, lang)].map(q).join(', ')}]

[extra]
schema = "term"
seo_title = ${q(t.title || t.title_cs ? title : `${title} (${tr(`kind_term_${t.kind}`, lang).toLowerCase()})`)}
term = ${q(t.id)}
kind = ${q(t.kind)}
definition = ${q(definition)}
aliases = [${(t.aliases ?? []).filter((a) => a !== name).map(q).join(', ')}]
reference = { title = ${q(t.reference.title)}, url = ${q(t.reference.url)} }
pages = [${usage.get(t.id)[lang].map(q).join(', ')}]
related = [${related.map(q).join(', ')}]
og_title = ${q(`${name}: ${tr('glossary', lang).toLowerCase()}`)}
og_image = ${q(`og/${cs ? 'cs-' : ''}glossary-${t.id}.png`)}
keywords = [${[title, name, t.term, tr(`kind_term_${t.kind}`, lang), tr('glossary', lang), cs ? 'Tomáš Korčák' : 'Tomas Korcak'].filter((k, i, a) => k.length > 1 && a.indexOf(k) === i).map(q).join(', ')}]
+++
`);
  });
}

mkdirSync(DIR, { recursive: true });
const findings = [];
for (const [name, text] of wanted) {
  const path = join(DIR, name);
  if (CHECK) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) findings.push(`content/glossary/${name} is missing or stale`);
  } else {
    writeFileSync(path, text);
  }
}
for (const name of readdirSync(DIR)) {
  if (wanted.has(name) || !readFileSync(join(DIR, name), 'utf8').includes(MARK)) continue;
  if (CHECK) findings.push(`content/glossary/${name} has no term any more`);
  else unlinkSync(join(DIR, name));
}
if (CHECK && findings.length) {
  for (const f of findings) console.error(`✗ ${f}; run node scripts/build-glossary.mjs`);
  process.exit(1);
}
console.log(`glossary: ${g.terms.length} terms x 2 languages ${CHECK ? 'current' : 'written'}`);
