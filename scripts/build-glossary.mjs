#!/usr/bin/env node
// Derives the glossary, content/glossary/, from data/glossary.toml: one page per term and language
// and the section page. Where a term is used and which terms are related are derived from the
// front matter of every other page (extra.terms): a page that names a term links to it, and the
// term's page links back. Nothing in these files is written by hand.
//
// usage: node scripts/build-glossary.mjs           write them (and remove stale ones)
//        node scripts/build-glossary.mjs --check   exit 1 if any is missing, stale or orphaned
import { join } from 'node:path';
import { CONTENT, ROOT, clip, contentPages, identity, languages, limits, local, ogPrefix, q, suffix, writeOrCheck } from './lib/derive.mjs';
import { loadGlossary, tl } from './lib/terms.mjs';
import { vizBlock } from './lib/viz.mjs';
import { loadStrings } from './lib/strings.mjs';

const DIR = join(CONTENT, 'glossary');
const MARK = '# generated by scripts/build-glossary.mjs from data/glossary.toml; do not edit';
const g = loadGlossary(ROOT);
const strings = loadStrings();
const tr = (key, lang) => strings[key][lang];
const me = identity();
const LIMITS = limits();
const LANGS = languages();

// Every page outside the glossary that names terms: its Zola path (as get_page takes it) by language.
// Co-occurrence is counted in the default language, where every page exists (check-i18n).
const usage = new Map(g.terms.map((t) => [t.id, Object.fromEntries(LANGS.map((l) => [l, []]))]));
const together = new Map(g.terms.map((t) => [t.id, new Map()]));
for (const page of contentPages()) {
  if (page.rel.startsWith('glossary/')) continue;
  const terms = page.fm?.extra?.terms ?? [];
  const { rel: path, lang } = page;
  for (const id of terms) {
    if (!usage.has(id)) continue; // check-glossary reports unknown ids
    usage.get(id)[lang].push(path);
    if (lang === LANGS[0]) for (const other of terms) if (other !== id && usage.has(other)) together.get(id).set(other, (together.get(id).get(other) ?? 0) + 1);
  }
}

const describe = (text, lang) => clip(text, LIMITS.description.max, { min: LIMITS.description.min, pad: tr('glossary_term_pad', lang) });
const KINDS = ['language', 'technology', 'concept'];
const sorted = [...g.terms].sort((a, b) => KINDS.indexOf(a.kind) - KINDS.indexOf(b.kind) || a.term.localeCompare(b.term));

const wanted = new Map();
for (const lang of LANGS) {
  const sfx = suffix(lang);
  wanted.set(`_index${sfx}.md`, `+++
${MARK}
title = ${q(tr('glossary', lang))}
description = ${q(tr('glossary_lead', lang).replace('{n}', g.terms.length))}
template = "glossary.html"
page_template = "term.html"
sort_by = "weight"

[extra]
og_title = ${q(tr('glossary_og', lang).replace('{n}', g.terms.length))}
og_image = ${q(`og/${ogPrefix(lang)}glossary.png`)}
schema = "glossary"
terms = ["open-source", "repository", "front-matter", "static-site-generator"]
keywords = [${[tr('glossary', lang), ...sorted.filter((t) => t.term.length > 1).slice(0, 10).map((t) => t.term), me.nameIn(lang)].map(q).join(', ')}]
${vizBlock({ kind: 'atlas', source: 'glossary.terms', title: 'viz_atlas_title', lead: 'viz_atlas_lead', height: 'lg' })}+++
${tl(g, 'derive_glossary_article', lang)}
`);
  sorted.forEach((t, position) => {
    const name = local(t, 'term', lang) || t.term;
    const definition = local(t, 'definition', lang);
    const related = [...together.get(t.id)].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 8).map(([id]) => id);
    const title = local(t, 'title', lang) ?? name;
    wanted.set(`${t.id}${sfx}.md`, `+++
${MARK}
title = ${q(title)}
description = ${q(describe(definition, lang))}
template = "term.html"
weight = ${position + 1}

[taxonomies]
tags = [${[tr('glossary', lang), tr(`kind_term_${t.kind}`, lang)].map(q).join(', ')}]

[extra]
schema = "term"
seo_title = ${q(t.title || t.title_cs ? title : `${title} (${tr(`kind_term_${t.kind}`, lang).toLowerCase()})`)}
term = ${q(t.id)}
kind = ${q(t.kind)}
definition = ${q(definition)}
aliases = [${(t.aliases ?? []).filter((a) => a !== name).map(q).join(', ')}]
reference = { title = ${q(t.reference.title)}, url = ${q(t.reference.url)} }
pages = [${usage.get(t.id)[lang].map(q).join(', ')}]
related = [${related.map(q).join(', ')}]
og_title = ${q(`${name}: ${tr('glossary', lang).toLowerCase()}`)}
og_image = ${q(`og/${ogPrefix(lang)}glossary-${t.id}.png`)}
keywords = [${[title, name, t.term, tr(`kind_term_${t.kind}`, lang), tr('glossary', lang), me.nameIn(lang)].filter((k, i, a) => k.length > 1 && a.indexOf(k) === i).map(q).join(', ')}]
${vizBlock({ kind: 'atlas', source: 'glossary.terms', title: 'viz_atlas_term_title', lead: 'viz_atlas_term_lead' })}+++
`);
  });
}

writeOrCheck(wanted, { dir: DIR, mark: MARK, label: 'glossary', orphanWhy: 'has no term any more' });
console.log(`glossary: ${g.terms.length} terms x ${LANGS.length} languages`);
