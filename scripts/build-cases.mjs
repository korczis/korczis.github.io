#!/usr/bin/env node
// Derives the case studies: content/cases/ (one page per client engagement of data/experience.json
// that has measurable sources, and the section), in every language. Everything on them is derived
// and anonymised (ADR 0006, ADR 0010): the sector and the roles the owner declared, the period and
// the rounded scale measured from the git history, the capabilities inferred from commits, paths and
// headings (labelled as an inference, never as a result), the technologies detected in the sources,
// the services and skills they feed (data/services.toml), and the public repositories that show the
// same skills. No client, person, system or repository name of the engagement ever reaches a page.
//
// usage: node scripts/build-cases.mjs           write them (and remove stale ones)
//        node scripts/build-cases.mjs --check   exit 1 if any is missing, stale or orphaned
import { join } from 'node:path';
import { ROOT, clip, identity, languages, limits, local, ogPrefix, q, readJson, readToml, suffix, t, writeOrCheck } from './lib/derive.mjs';
import { listing, loadGlossary, mdEscape, nameLink, tl } from './lib/terms.mjs';
import { cliArgs } from './lib/cli.mjs';

cliArgs({ '--check': true }, { derived: true });

const MARK = '# generated by scripts/build-cases.mjs from data/experience.json; do not edit';
const g = loadGlossary(ROOT);
const me = identity();
const rules = readToml('data/experience-rules.toml');
const xp = readJson('data/experience.json');
const services = readToml('data/services.toml').services ?? [];
const recent = readJson('data/recent.json');
const LANGS = languages();
const LIMITS = limits();
const SOLVED = rules.display?.solved ?? 4;
const TITLE_MAX = readJson('static/schemas/front-matter.schema.json').properties.title.maxLength;

const uniq = (xs) => [...new Set(xs.filter(Boolean))];
const sectorName = (key, lang) => local(rules.sectors?.[key], 'name', lang) ?? key;
const roleName = (key, lang) => local(rules.roles?.[key], 'name', lang) ?? key;
const capName = (key, lang) => local(rules.capabilities[key], 'name', lang) ?? key;
const capDesc = (key, lang) => local(rules.capabilities[key], 'description', lang) ?? '';
const domainName = (key, lang) => local(rules.domains?.[key], 'name', lang) ?? key;
const skillLink = (key, lang) => `[${capName(key, lang)}](@/skills/${key}${suffix(lang)}.md)`;
const serviceLink = (s, lang) => `[${local(s, 'name', lang)}](@/services/${s.id}${suffix(lang)}.md)`;
const months = (lang) => t('derive_months', lang).split(',');
const monthText = (ym, lang) => `${months(lang)[Number(ym.slice(5, 7)) - 1]} ${ym.slice(0, 4)}`;
const workOf = new Set(recent.repos.map((r) => r.name));
const repoLink = (name, lang) => (workOf.has(name)
  ? `[${mdEscape(name)}](@/work/${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}${suffix(lang)}.md)`
  : mdEscape(name));

// A case is an engagement with a sector and at least one inferred capability; the others have no
// measurable sources and are only counted (the landing says so too).
const cases = xp.engagements.filter((e) => e.sector && e.capabilities.length > 0);
const slugOf = (e) => e.sector;
const capsOf = (e) => e.capabilities.map((c) => c.key);
const domainsOf = (e) => {
  const order = rules.domain_order ?? [];
  return uniq(capsOf(e).map((k) => rules.capabilities[k]?.domain)).sort((a, b) => order.indexOf(a) - order.indexOf(b));
};
// The services whose skills this case covers best: at least half of a service's skills, or the two
// best when none reaches half; each with its overlap, so the claim is exactly as strong as the data.
const servicesOf = (e) => {
  const ranked = services.map((s) => ({ s, hit: s.skills.filter((k) => capsOf(e).includes(k)).length, of: s.skills.length }))
    .filter((x) => x.hit > 0).sort((a, b) => b.hit / b.of - a.hit / a.of || b.hit - a.hit);
  const half = ranked.filter((x) => x.hit * 2 >= x.of);
  return half.length ? half : ranked.slice(0, 2);
};
// A label inside a sentence: lower-case its first letter unless it starts an acronym (LLM, OSINT).
const lc = (x) => (/^\p{Lu}\p{Ll}/u.test(x) ? x[0].toLocaleLowerCase() + x.slice(1) : x);
const num = (n, lang) => new Intl.NumberFormat(lang === 'cs' ? 'cs-CZ' : 'en-GB').format(n);
const publicOf = (e) => uniq(capsOf(e).flatMap((k) => xp.public_work?.[k] ?? []));
const termIdsOf = (e) => uniq([
  'case-study',
  ...capsOf(e).map((k) => rules.capabilities[k]?.term),
  ...e.technologies.map((name) => g.byName.get(String(name).toLowerCase())),
]).filter((id) => g.byId.has(id));
// The sector and its two strongest capabilities, or the strongest alone when that is too long.
const titleOf = (e, lang) => {
  const of = (n) => t('derive_case_title', lang, { sector: sectorName(e.sector, lang), skills: listing(capsOf(e).slice(0, n).map((k, i) => (i ? lc(capName(k, lang)) : capName(k, lang))), lang) });
  // The page title also carries " · <author>" in <title> (templates/partials/seo.html).
  const max = Math.min(TITLE_MAX, LIMITS.title.max - me.nameIn(lang).length - 3);
  return of(2).length <= max ? of(2) : of(1);
};
const describe = (e, lang) => clip(t('derive_case_description', lang, {
  sector: lc(sectorName(e.sector, lang)),
  roles: listing(e.roles.map((r) => lc(roleName(r, lang))), lang),
  skills: listing(capsOf(e).slice(0, 2).map((k) => lc(capName(k, lang))), lang),
}), LIMITS.description.max, { min: LIMITS.description.min, pad: t('derive_case_pad', lang) });

function article(e, lang) {
  const p = [tl(g, 'derive_case_context', lang, { sector: sectorName(e.sector, lang) })];
  if (e.roles.length) {
    p.push(t('derive_case_role', lang));
    p.push(e.roles.map((r) => `- **${roleName(r, lang)}**: ${local(rules.roles[r], 'description', lang)}`).join('\n'));
  }
  if (e.period) {
    const n = Object.keys(e.months ?? {}).length;
    p.push(t('derive_case_period', lang, { from: monthText(e.period.from, lang), to: monthText(e.period.to, lang), n }));
  }
  p.push(t('derive_case_delivered', lang, { n: SOLVED }));
  p.push(capsOf(e).slice(0, SOLVED).map((k) => `- ${skillLink(k, lang)}: ${capDesc(k, lang)}`).join('\n'));
  if (capsOf(e).length > SOLVED) p.push(t('derive_case_more', lang, { list: listing(capsOf(e).slice(SOLVED).map((k) => skillLink(k, lang)), lang) }));
  const sc = e.scale ?? {};
  if (sc.commits) p.push(t(sc.tests ? 'derive_case_scale' : 'derive_case_scale_untested', lang, { commits: num(sc.commits, lang), repositories: num(sc.repositories, lang), team: num(sc.team, lang), files: num(sc.files, lang), tests: num(sc.tests, lang) }));
  const tech = e.technologies.map((name) => nameLink(g, name, lang));
  if (tech.length) p.push(t('derive_case_tech', lang, { list: listing(tech, lang) }));
  const sv = servicesOf(e);
  if (sv.length) p.push(t('derive_case_services', lang, { list: listing(sv.map((x) => t('derive_case_service_item', lang, { link: serviceLink(x.s, lang), hit: x.hit, of: x.of })), lang) }));
  const pub = publicOf(e);
  if (pub.length) p.push(t('derive_case_public', lang, { list: listing(pub.map((name) => repoLink(name, lang)), lang) }));
  p.push(t('derive_case_limits', lang, { landing: `@/_index${suffix(lang)}.md` }));
  return p.join('\n\n');
}

const files = new Map();
for (const lang of LANGS) {
  const sfx = suffix(lang);
  const rest = xp.engagements.length - cases.length;
  const intro = [
    t('derive_cases_intro', lang, { n: cases.length, list: listing(cases.map((e) => `[${titleOf(e, lang)}](@/cases/${slugOf(e)}${sfx}.md)`), lang) }),
    rest > 0 ? t('derive_cases_rest', lang, { n: rest }) : '',
    t('derive_cases_flagship', lang, { link: `[Majordomus](@/work/prismatic-majordomus${sfx}.md)` }),
    tl(g, 'derive_cases_how', lang),
  ].filter(Boolean);
  files.set(`_index${sfx}.md`, `+++
${MARK}
title = ${q(t('cases_title', lang))}
description = ${q(clip(t('cases_lead', lang), LIMITS.description.max, { min: LIMITS.description.min, pad: t('derive_case_pad', lang) }))}
template = "cases.html"
page_template = "case.html"
sort_by = "weight"

[extra]
og_title = ${q(t('cases_og', lang, { n: cases.length }))}
og_image = ${q(`og/${ogPrefix(lang)}cases.png`)}
schema = "collection"
terms = [${uniq(cases.flatMap(termIdsOf)).slice(0, 16).map(q).join(', ')}]
keywords = [${[t('cases_title', lang), ...cases.map((e) => sectorName(e.sector, lang)), me.nameIn(lang)].map(q).join(', ')}]
+++
${intro.join('\n\n')}
`);
  cases.forEach((e, i) => {
    files.set(`${slugOf(e)}${sfx}.md`, `+++
${MARK}
title = ${q(titleOf(e, lang))}
description = ${q(describe(e, lang))}
template = "case.html"
weight = ${i + 1}

[taxonomies]
tags = [${[t('cases_title', lang), ...domainsOf(e).map((d) => domainName(d, lang))].map(q).join(', ')}]

[extra]
engagement = ${q(e.id)}
case_services = [${servicesOf(e).map((x) => `{ id = ${q(x.s.id)}, hit = ${x.hit}, of = ${x.of} }`).join(', ')}]
case_public = [${publicOf(e).map(q).join(', ')}]
og_title = ${q(titleOf(e, lang))}
og_image = ${q(`og/${ogPrefix(lang)}case-${slugOf(e)}.png`)}
schema = "case"
terms = [${termIdsOf(e).slice(0, 16).map(q).join(', ')}]
keywords = [${[sectorName(e.sector, lang), ...capsOf(e).slice(0, 6).map((k) => capName(k, lang)), ...e.technologies.slice(0, 4), me.nameIn(lang)].map(q).join(', ')}]
+++
${article(e, lang)}
`);
  });
}

writeOrCheck(files, { dir: join(ROOT, 'content/cases'), mark: MARK, label: 'cases', orphanWhy: 'has no engagement with measurable sources any more' });
