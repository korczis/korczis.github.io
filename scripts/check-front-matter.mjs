#!/usr/bin/env node
// Gate for the front-matter contract (static/schemas/front-matter.schema.json, served at /schemas/): every content/*.md has
// front matter that matches it, category pages name a real category, and og_image names are
// unique. The schema is the machine-readable description; this checks exactly its rules (no
// dependency): required keys, no unknown keys, types, lengths, patterns, enums, array sizes.
import { ROOT, contentPages, readJson, readToml } from './lib/derive.mjs';
import { loadGlossary } from './lib/terms.mjs';

const schema = readJson('static/schemas/front-matter.schema.json');
const catalogue = readToml('data/projects.toml');
const findings = [];

function validate(value, rule, where) {
  if (rule.enum && !rule.enum.includes(value)) return findings.push(`${where}: ${JSON.stringify(value)} is not one of ${rule.enum.join(', ')}`);
  const type = Array.isArray(value) ? 'array' : Number.isInteger(value) ? 'integer' : typeof value;
  if (rule.type && rule.type !== type) return findings.push(`${where}: expected ${rule.type}, got ${type}`);
  if (type === 'string') {
    if (rule.minLength && value.length < rule.minLength) findings.push(`${where}: ${value.length} characters, at least ${rule.minLength}`);
    if (rule.maxLength && value.length > rule.maxLength) findings.push(`${where}: ${value.length} characters, at most ${rule.maxLength}`);
    if (rule.pattern && !new RegExp(rule.pattern).test(value)) findings.push(`${where}: does not match ${rule.pattern}`);
  }
  if (type === 'integer' && rule.minimum !== undefined && value < rule.minimum) findings.push(`${where}: below ${rule.minimum}`);
  if (type === 'array') {
    if (rule.minItems && value.length < rule.minItems) findings.push(`${where}: ${value.length} items, at least ${rule.minItems}`);
    if (rule.maxItems && value.length > rule.maxItems) findings.push(`${where}: ${value.length} items, at most ${rule.maxItems}`);
    value.forEach((item, i) => validate(item, rule.items ?? {}, `${where}[${i}]`));
  }
  if (type === 'object') {
    for (const key of rule.required ?? []) if (!(key in value)) findings.push(`${where}: missing ${key}`);
    for (const [key, v] of Object.entries(value)) {
      if (!rule.properties?.[key]) {
        if (rule.additionalProperties === false) findings.push(`${where}: unknown key ${key}`);
        continue;
      }
      validate(v, rule.properties[key], `${where}.${key}`);
    }
  }
}

const images = new Map();
const pages = contentPages();
for (const { path: rel, fm } of pages) {
  if (!fm) { findings.push(`${rel}: no TOML front matter`); continue; }
  validate(fm, { ...schema, type: 'object' }, rel);
  const category = fm.extra?.category;
  if (category && !(category in catalogue.categories)) findings.push(`${rel}: extra.category ${category} is not in data/projects.toml`);
  const image = fm.extra?.og_image;
  if (image && images.has(image)) findings.push(`${rel}: og_image ${image} is also used by ${images.get(image)}`);
  if (image) images.set(image, rel);
}

// Hand-written front matter that names facts the data measures must agree with the data (F12):
//   - a measured language a hand page names (keyword or term) is one of the top [index]
//     top_languages of data/index.json, so "Elixir, Rust" cannot outlive Rust's place;
//   - a curated project a hand page names in its keywords is featured in data/projects.toml;
//   - the stack page (template stack.html) names every tool of data/site.toml [[stack.tools]] as a
//     term, and its keywords name no technology outside them.
const GENERATED = /^# generated by scripts\//m;
const index = readJson('data/index.json');
const site = readToml('data/site.toml');
const glossary = loadGlossary(ROOT);
const topN = catalogue.index.top_languages;
const measured = new Set(index.languages.map((l) => l.name.toLowerCase()));
const top = new Set(index.languages.slice(0, topN).map((l) => l.name.toLowerCase()));
const projectNames = new Map(catalogue.projects.map((p) => [p.name.toLowerCase(), p]));
const termName = (id) => glossary.byId.get(id)?.term ?? id;
const tools = (site.stack?.tools ?? []).map((t) => t.name);
const toolTerms = new Set(tools.map((n) => glossary.byName.get(n.toLowerCase())).filter(Boolean));
let crossChecked = 0;
for (const { path: rel, fm, text } of pages) {
  if (!fm || GENERATED.test(text)) continue;
  crossChecked += 1;
  const named = [...(fm.extra?.keywords ?? []), ...(fm.extra?.terms ?? []).map(termName)];
  for (const name of named) {
    const key = name.toLowerCase();
    if (measured.has(key) && !top.has(key)) findings.push(`${rel}: names ${name}, which is not among the top ${topN} measured languages (${[...top].join(', ')})`);
  }
  for (const k of fm.extra?.keywords ?? []) {
    const p = projectNames.get(k.toLowerCase());
    if (p && !p.featured) findings.push(`${rel}: keyword ${k} names a project that is not featured in data/projects.toml`);
  }
  if (fm.template === 'stack.html') {
    for (const tool of tools) {
      const id = glossary.byName.get(tool.toLowerCase());
      if (id && !(fm.extra?.terms ?? []).includes(id)) findings.push(`${rel}: data/site.toml stack tool ${tool} is not in extra.terms`);
    }
    for (const k of fm.extra?.keywords ?? []) {
      const id = glossary.byName.get(k.toLowerCase());
      if (id && glossary.byId.get(id).kind === 'technology' && !toolTerms.has(id)) findings.push(`${rel}: keyword ${k} is no tool of data/site.toml [[stack.tools]]`);
    }
  }
}

if (findings.length) {
  for (const f of findings) console.error(`✗ ${f}`);
  process.exit(1);
}
console.log(`front matter: ${pages.length} pages match static/schemas/front-matter.schema.json (${images.size} OG images), ${crossChecked} hand pages agree with the data, PASS`);
