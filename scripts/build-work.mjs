#!/usr/bin/env node
// Derives one Zola page per repository with a commit in the last 48 months, content/work/<name>.md,
// from data/recent.json: title, description, SEO and OG front matter. The page itself
// (templates/work.html) renders everything else from the data. Nothing here is written by hand.
//
// usage: node scripts/build-work.mjs           write them (and remove stale ones)
//        node scripts/build-work.mjs --check   exit 1 if any is missing, stale or orphaned
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'content/work');
const CHECK = process.argv.includes('--check');
const MARK = '# generated by scripts/build-work.mjs from data/recent.json; do not edit';
const catalogue = parse(readFileSync(join(ROOT, 'data/projects.toml'), 'utf8'));
const recent = JSON.parse(readFileSync(join(ROOT, 'data/recent.json'), 'utf8'));
const q = (s) => JSON.stringify(s);
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// A description of 50-165 characters from the repository's own words (description, else README).
function describe(r) {
  const curated = catalogue.projects.find((p) => p.repo === r.name);
  const words = [curated?.tagline, r.description, r.readme].filter(Boolean).map((t) => t.replace(/\s+/g, ' ').trim());
  let text = words.find((t) => t.length >= 50) ?? `${words[0] ?? r.name}. Active in the last ${r.period} months; ${catalogue.categories[r.category].name.toLowerCase()}.`;
  if (text.length > 165) text = `${text.slice(0, 162).replace(/\s+\S*$/, '')}…`;
  if (text.length < 50) text = `${text} A project by Tomas Korcak, active in the last ${r.period} months.`;
  return text;
}

// Deterministic on every machine: UTC and our own month names (locale data and time zones differ
// between this Mac and CI, and a generated file must come out byte-identical everywhere).
const CS_MONTHS = ['ledna', 'února', 'března', 'dubna', 'května', 'června', 'července', 'srpna', 'září', 'října', 'listopadu', 'prosince'];
const csDate = (iso) => { const d = new Date(iso); return `${d.getUTCDate()}. ${CS_MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`; };
const csProjects = (n) => (n === 1 ? 'projekt' : n >= 2 && n <= 4 ? 'projekty' : 'projektů');
// The Czech description is derived from the data, never machine-translated prose: category,
// language and the date of the last commit, or the curated Czech tagline when there is one.
function describeCs(r) {
  const curated = catalogue.projects.find((p) => p.repo === r.name);
  if (curated?.summary_cs && curated.summary_cs.length >= 50) return curated.summary_cs.length > 165 ? `${curated.summary_cs.slice(0, 162).replace(/\s+\S*$/, '')}…` : curated.summary_cs;
  const lang = r.languages[0]?.name ?? r.language;
  return `${curated?.name ?? r.name}: projekt z kategorie ${catalogue.categories[r.category].name_cs}${lang ? `, hlavní jazyk ${lang}` : ''}, poslední commit ${csDate(r.last_commit)}.`;
}
const tags = (r, cs) => [cs ? catalogue.categories[r.category].name_cs : catalogue.categories[r.category].name, ...r.languages.slice(0, 3).map((l) => l.name)];

const wanted = new Map();
for (const lang of ['en', 'cs']) {
  const cs = lang === 'cs';
  wanted.set(cs ? '_index.cs.md' : '_index.md', `+++
${MARK}
title = ${q(cs ? 'Nedávná práce' : 'Recent work')}
description = ${q(cs
    ? `Každý projekt s commitem za posledních 48 měsíců, podle období (12, 24, 48): ${recent.repos.length} repozitářů na GitHubu a GitLabu, každý s vlastní stránkou.`
    : `Every project with a commit in the last 48 months, by period (12, 24, 48): ${recent.repos.length} repositories on GitHub and GitLab, each with its own page.`)}
template = "work-list.html"
sort_by = "weight"

[extra]
og_title = ${q(cs ? `${recent.repos.length} ${csProjects(recent.repos.length)} za poslední čtyři roky.` : `${recent.repos.length} projects, the last four years.`)}
og_image = ${q(cs ? 'og/cs-work.png' : 'og/work.png')}
schema = "collection"
keywords = [${[cs ? 'nedávná práce Tomáše Korčáka' : 'Tomas Korcak recent work', 'korczis', ...recent.repos.slice(0, 8).map((r) => r.name)].map(q).join(', ')}]
+++
`);
  recent.repos.forEach((r, position) => {
    const curated = catalogue.projects.find((p) => p.repo === r.name);
    const title = curated?.name ?? r.name;
    const tagline = cs ? (curated?.tagline_cs ?? catalogue.categories[r.category].name_cs) : (curated?.tagline ?? r.description ?? catalogue.categories[r.category].name);
    wanted.set(`${slug(r.name)}${cs ? '.cs' : ''}.md`, `+++
${MARK}
title = ${q(title)}
description = ${q(cs ? describeCs(r) : describe(r))}
template = "work.html"
weight = ${position + 1}

[taxonomies]
tags = [${tags(r, cs).map(q).join(', ')}]

[extra]
repo = ${q(r.name)}
og_title = ${q(`${title}: ${tagline}`.slice(0, 90))}
og_image = ${q(`og/${cs ? 'cs-' : ''}work-${slug(r.name)}.png`)}
schema = "project"
keywords = [${[title, ...tags(r, cs), cs ? 'Tomáš Korčák' : 'Tomas Korcak'].map(q).join(', ')}]
+++
`);
  });
}

mkdirSync(DIR, { recursive: true });
const findings = [];
for (const [name, text] of wanted) {
  const path = join(DIR, name);
  if (CHECK) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) findings.push(`content/work/${name} is missing or stale`);
  } else {
    writeFileSync(path, text);
  }
}
for (const name of readdirSync(DIR)) {
  if (wanted.has(name) || !readFileSync(join(DIR, name), 'utf8').includes(MARK)) continue;
  if (CHECK) findings.push(`content/work/${name} has no recent repository any more`);
  else unlinkSync(join(DIR, name));
}
if (CHECK && findings.length) {
  for (const f of findings) console.error(`✗ ${f}; run node scripts/build-work.mjs`);
  process.exit(1);
}
console.log(`work: ${wanted.size - 1} project pages and the list ${CHECK ? 'current' : 'written'}`);
