#!/usr/bin/env node
// Derives one Zola page per original repository, content/work/<slug>.md in every language, and the
// list page, from data/recent.json (which holds every original repository of data/index.json, the
// one set: ADR 0003). A repository with a commit in the recent window is dated by its period, every
// other one is archive, dated by its first and last year. Title, description, SEO title, Open
// Graph front matter, keywords, terms and the article are derived from measured facts (name, own
// words, languages, years, category, stars, live site, forges, supervision); the page itself
// (templates/work.html) renders everything else from the data. Nothing here is written by hand;
// the prose is i18n/derive.toml.
//
// usage: node scripts/build-work.mjs           write them (and remove stale ones)
//        node scripts/build-work.mjs --check   exit 1 if any is missing, stale or orphaned, or an
//                                              original repository of data/index.json has no page
import { join } from 'node:path';
import {
  ROOT, cadence, clip, identity, isDefault, languages, limits, local, ogPrefix, q, readJson, readToml, report, slug, suffix, t, writeOrCheck,
} from './lib/derive.mjs';
import { REPOSITORY_TERMS, linkedTerms, listing, loadGlossary, mdEscape, nameLink, onGithubPages, termsForRepo, tl } from './lib/terms.mjs';
import { vizBlock } from './lib/viz.mjs';
import { cliArgs } from './lib/cli.mjs';
import { loadDossierStacks } from './lib/skills.mjs';

cliArgs({ '--check': true }, { derived: true });

const DIR = join(ROOT, 'content/work');
const MARK = '# generated by scripts/build-work.mjs from data/recent.json; do not edit';
const catalogue = readToml('data/projects.toml');
const recent = readJson('data/recent.json');
const index = readJson('data/index.json');
const glossary = loadGlossary(ROOT);
const DOSSIER_STACKS = loadDossierStacks();
const me = identity();
const LIMITS = limits();
const periods = recent.periods.map((p) => p.months);
const refresh = cadence();
// How often the data is measured, in words: "every 6 hours" (from .github/workflows/refresh.yml).
const cadenceIn = (lang) => t(`derive_cadence_${refresh.unit}`, lang, { n: refresh.n });

// The one set: every original repository of the index has its page, and no page has no repository.
{
  const measured = new Set(recent.repos.map((r) => r.name));
  const listed = new Set(index.repos.map((r) => r.name));
  const slugs = new Map();
  const clashes = [];
  for (const r of recent.repos) {
    if (slugs.has(slug(r.name))) clashes.push(`${r.name} and ${slugs.get(slug(r.name))} share the page slug ${slug(r.name)}`);
    slugs.set(slug(r.name), r.name);
  }
  report([
    ...index.repos.filter((r) => !measured.has(r.name)).map((r) => `${r.name} is an original repository of data/index.json without a measurement in data/recent.json (npm run recent)`),
    ...recent.repos.filter((r) => !listed.has(r.name)).map((r) => `${r.name} is in data/recent.json but no original repository of data/index.json`),
    ...clashes,
  ]);
}

// The window as words: "the last 4 years", or months when it is not whole years.
const span = (lang) => (periods.at(-1) % 12 === 0
  ? t('derive_last_years', lang, { n: periods.at(-1) / 12 })
  : t('derive_last_months', lang, { n: periods.at(-1) }));
const curatedOf = (r) => catalogue.projects.find((p) => p.repo === r.name);
const categoryName = (r, lang) => local(catalogue.categories[r.category], 'name', lang);
const archived = (r) => r.period === null;

// Deterministic on every machine: UTC and the month names of i18n (locale data and time zones
// differ between this Mac and CI, and a generated file must come out byte-identical everywhere).
const months = (lang) => t('derive_months', lang).split(',');
const date = (iso, lang) => { const d = new Date(iso); return t('derive_date', lang, { day: d.getUTCDate(), month: months(lang)[d.getUTCMonth()], year: d.getUTCFullYear() }); };
const share = (n, lang) => new Intl.NumberFormat(lang, { maximumFractionDigits: 1, useGrouping: false }).format(n);

// The measured dates of a repository: its last commit (the host's last push when no commit could be
// read), and its first year, the earlier of the host's creation date and the oldest commit read
// (GitLab dates an imported project by its import day; its commits are older).
const lastAt = (r) => r.last_commit ?? r.pushed_at;
const firstYear = (r) => Math.min(...[r.created_at, ...r.commits.map((c) => c.at)].filter(Boolean).map((x) => new Date(x).getUTCFullYear()));
const lastYear = (r) => new Date(lastAt(r)).getUTCFullYear();
const years = (r) => (firstYear(r) >= lastYear(r) ? String(lastYear(r)) : `${firstYear(r)}–${lastYear(r)}`);
const mainLanguage = (r) => r.languages[0]?.name ?? r.language ?? null;
// The languages of a repository: the measured breakdown by bytes, else the index's primary
// language alone (share unknown: a forge that reported no breakdown still named it).
const langsOf = (r) => (r.languages.length ? r.languages : r.language ? [{ name: r.language, share: null }] : []);

// Which language a text a repository wrote itself is in: Czech when its letters carry Czech
// diacritics (ě š č ř ž ů ...), the default language otherwise. Its own words are shown only on the
// page of their language; the other language gets the sentence derived from the data, never a
// machine translation (rule project.i18n-everywhere).
const CZECH = /[ěščřžýáíéůúťďňó]/gi;
function textLanguage(text) {
  const letters = (text.match(/\p{L}/gu) ?? []).length;
  return letters && (text.match(CZECH) ?? []).length / letters > 0.02 ? 'cs' : languages()[0];
}
// The README excerpt counts only when it is the repository's own: one that several repositories
// share verbatim (readme_shared, measured by scripts/fetch-recent.mjs) is a generator's or a
// template's text ("Now you can visit localhost:4000 from your browser."), never a description.
// The repository's own description comes before its README, however short.
const ownWords = (r, lang) => [local(curatedOf(r), 'tagline', lang), ...[r.description, r.readme_shared ? null : r.readme].filter((x) => x && textLanguage(x) === lang)]
  .filter(Boolean).map((x) => x.replace(/\s+/g, ' ').trim());

// A description within the schema's limits: the repository's own words in this language (curated
// tagline, else description, else README), whole when long enough and its own, else within a
// sentence that adds its state and category (and its name, when other repositories use the same
// words: description_shared), else a sentence derived from the data (category, language, years,
// last commit). Every description is unique (check-seo).
function describe(r, lang) {
  const { min, max } = LIMITS.description;
  const curated = curatedOf(r);
  const name = curated?.name ?? r.name;
  const summary = local(curated, 'summary', lang);
  if (!isDefault(lang) && summary && summary.length >= min) return clip(summary, max);
  const words = ownWords(r, lang);
  const language = mainLanguage(r);
  const vars = {
    name, text: words[0]?.replace(/[.!]+$/, '') ?? name, period: r.period, years: years(r), author: me.nameIn(lang),
    category: categoryName(r, lang), lower: categoryName(r, lang).toLowerCase(),
    language: language ? t('derive_work_description_language', lang, { language }) : '',
    last: date(lastAt(r), lang),
  };
  const kind = archived(r) ? '_archive' : '';
  const own = words[0];
  const shared = own && own === r.description?.replace(/\s+/g, ' ').trim() && r.description_shared;
  if (shared) vars.text = t('derive_work_named', lang, { name, text: vars.text });
  const text = own && own.length >= min && !shared ? own
    : own ? t(`derive_work_description_fallback${kind}`, lang, vars) : t(`derive_work_description${kind}`, lang, vars);
  return clip(text, max, { min, pad: t(`derive_work_description_pad${kind}`, lang, vars) });
}

// The short "what it is" of a repository in a language: the first sentence of its own words
// (tagline, else description, else README), without a leading repeat of its name ("lethe.it -
// your personal ..."), when it fits; else its category and main language.
const escapeRe = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function what(r, lang, max) {
  const own = ownWords(r, lang)[0];
  if (own) {
    const first = (own.match(/^(.{20,}?[.!?])(\s|$)/)?.[1] ?? own).replace(/[.!]+$/, '');
    const short = first.replace(new RegExp(`^${escapeRe(curatedOf(r)?.name ?? r.name)}\\s*[-–—:]\\s*`, 'i'), '');
    if (short.length >= 3 && short.length <= max) return short;
  }
  const language = mainLanguage(r);
  return language ? t('derive_work_seo_what', lang, { category: categoryName(r, lang), language }) : categoryName(r, lang);
}

// The <title>: name, what it is, years and author, within the schema's limit; the longest form
// that fits wins, never a cut word.
function seoTitle(r, lang) {
  const max = LIMITS.title.max;
  const name = curatedOf(r)?.name ?? r.name;
  const author = me.nameIn(lang);
  const language = mainLanguage(r);
  const plain = language ? t('derive_work_seo_what', lang, { category: categoryName(r, lang), language }) : categoryName(r, lang);
  const forms = [
    t('derive_work_seo_title', lang, { name, what: what(r, lang, max), years: years(r), author }),
    t('derive_work_seo_title', lang, { name, what: plain, years: years(r), author }),
    t('derive_work_seo_title', lang, { name, what: categoryName(r, lang), years: years(r), author }),
    t('derive_work_seo_title_short', lang, { name, years: years(r), author }),
  ];
  return forms.find((x) => x.length <= max) ?? clip(`${name} · ${author}`, max);
}

// The headline of the social card and og:title: name and what it is (and the years of an archive
// project), cut at a word.
function ogTitle(r, lang) {
  const { min, max } = LIMITS.ogTitle;
  const name = curatedOf(r)?.name ?? r.name;
  const key = archived(r) ? 'derive_work_og_title_archive' : 'derive_work_og_title';
  // "what" is cut at a word to the room the rest of the headline leaves, so the years stay.
  const room = max - t(key, lang, { name, what: '', years: years(r) }).length;
  const x = t(key, lang, { name, what: clip(what(r, lang, 200), Math.max(room, 12)), years: years(r) });
  return clip(x, max, { min, pad: categoryName(r, lang) });
}

// The card's and og:description's sentence: measured facts only (category, languages, years,
// state, forges, stars, live site, supervision).
function ogDescription(r, lang) {
  const { min, max } = LIMITS.description;
  const langs = langsOf(r).slice(0, 3).map((l) => l.name);
  const forges = [r.hosts.github && 'GitHub', r.hosts.gitlab && 'GitLab'].filter(Boolean);
  const facts = [
    t(langs.length ? 'derive_work_og_facts_languages' : 'derive_work_og_facts', lang, {
      name: curatedOf(r)?.name ?? r.name, category: categoryName(r, lang), list: listing(langs, lang), years: years(r),
      state: archived(r) ? t('derive_work_og_archive', lang) : t('derive_work_og_active', lang, { period: r.period }),
    }),
    t('derive_work_og_forges', lang, { list: listing(forges, lang) }),
    r.stars ? t('derive_work_og_stars', lang, { n: r.stars }) : '',
    r.site ? t('derive_work_og_site', lang) : '',
    r.supervised ? t('derive_work_og_supervised', lang) : '',
  ].filter(Boolean).join(' ');
  return clip(facts, max, { min, pad: t('derive_work_og_by', lang, { author: me.nameIn(lang) }) });
}

// Related work: the repositories of the same category closest to this one, by shared languages and
// then by time, the name breaking ties; derived, never chosen.
const RELATED = 4;
function related(r) {
  const mine = new Set(langsOf(r).map((l) => l.name));
  const at = Date.parse(lastAt(r));
  return recent.repos.filter((o) => o.name !== r.name && o.category === r.category)
    .map((o) => ({ o, shared: langsOf(o).filter((l) => mine.has(l.name)).length, gap: Math.abs(Date.parse(lastAt(o)) - at) }))
    .sort((a, b) => b.shared - a.shared || a.gap - b.gap || a.o.name.localeCompare(b.o.name))
    .slice(0, RELATED).map((x) => x.o);
}

// The article of a work page, derived from the measured data: what it is, what it is written in,
// when it began and last moved (or that it is archive), what it is built with, where it runs, where
// its source is, what is related and how to read the page. Every term links to the glossary and
// every related project to its page (Zola checks the links); the commit message stays verbatim.
function article(r, curated, lang) {
  const title = `**${mdEscape(curated?.name ?? r.name)}**`;
  const category = `[${categoryName(r, lang)}](@/projects/${r.category}${suffix(lang)}.md)`;
  const langs = langsOf(r).slice(0, 4);
  const p = [];
  if (langs.length) {
    const main = nameLink(glossary, langs[0].name, lang) + (langs[0].share === null ? '' : ` (${share(langs[0].share, lang)} %)`);
    const rest = listing(langs.slice(1).map((l) => nameLink(glossary, l.name, lang)), lang);
    p.push(t('derive_work_intro_languages', lang, { title, category, main, rest: rest ? t('derive_work_intro_rest', lang, { list: rest }) : '' }));
  } else {
    p.push(t('derive_work_intro', lang, { title, category }));
  }
  const message = r.last_message ? t('derive_work_message', lang, { message: mdEscape(r.last_message) }) : '';
  const history = r.last_commit ? (archived(r) ? 'derive_work_history_archive' : 'derive_work_history') : 'derive_work_history_unread';
  p.push(tl(glossary, history, lang, {
    created: date(r.created_at, lang), last: date(lastAt(r), lang), message,
    period: r.period, years: years(r), window: periods.at(-1),
  }));
  const stack = (curated?.stack ?? []).filter((n) => glossary.byName.has(n.toLowerCase()) && !langs.some((l) => l.name === n));
  if (stack.length) p.push(t('derive_work_stack', lang, { list: listing(stack.map((n) => nameLink(glossary, n, lang)), lang) }));
  if (r.site) {
    p.push(t('derive_work_site', lang, { site: r.site, pages: onGithubPages(r.site) ? tl(glossary, 'derive_work_site_pages', lang) : '' }));
  }
  const forges = [r.hosts.github && `[GitHub](${r.hosts.github})`, r.hosts.gitlab && `[GitLab](${r.hosts.gitlab})`].filter(Boolean);
  p.push(t('derive_work_forges', lang, { list: listing(forges, lang) }));
  const near = related(r);
  if (near.length) {
    p.push(t('derive_work_related', lang, {
      category, list: listing(near.map((o) => `[${mdEscape(curatedOf(o)?.name ?? o.name)}](@/work/${slug(o.name)}${suffix(lang)}.md) (${years(o)})`), lang),
    }));
  }
  p.push(t(r.commits.length ? 'derive_work_how' : 'derive_work_how_facts', lang, {
    shares: r.languages.length ? t('derive_work_how_shares', lang) : '',
    latest: t('derive_work_latest_commits', lang, { n: r.commits.length }),
    refresh: t(r.hosts.github ? 'derive_work_refresh_live' : 'derive_work_refresh_snapshot', lang, {
      cadence: cadenceIn(lang),
    }),
    glossary: `@/glossary/_index${suffix(lang)}.md`,
  }));
  return p.join('\n\n');
}

// Tags: the category and the top three languages. Zola addresses a tag by its slug, so languages
// whose slugs collide (C, C# and C++ are all /tags/c/) would share one page under one name: such a
// language is no tag (its glossary term and the repositories filter still lead to it).
const TAGGED = 3;
const tagSlugs = new Map();
for (const r of recent.repos) for (const l of langsOf(r).slice(0, TAGGED)) tagSlugs.set(slug(l.name), new Set([...(tagSlugs.get(slug(l.name)) ?? []), l.name]));
const ambiguous = (name) => (tagSlugs.get(slug(name))?.size ?? 0) > 1;
const tags = (r, lang) => [...new Set([categoryName(r, lang), ...langsOf(r).slice(0, TAGGED).map((l) => l.name).filter((n) => !ambiguous(n))])];
// Keywords: what a search for this project would name, all measured: name, category, languages,
// topics, years, forges and the author; within the schema's 16.
function keywords(r, lang) {
  const name = curatedOf(r)?.name ?? r.name;
  const words = [name, r.name, categoryName(r, lang), ...langsOf(r).slice(0, TAGGED).map((l) => l.name), ...(r.topics ?? []).slice(0, 6), years(r),
    r.hosts.github && 'GitHub', r.hosts.gitlab && 'GitLab', me.nameIn(lang), me.github];
  const seen = new Set();
  return words.filter((w) => {
    const key = String(w ?? '').toLowerCase();
    if (key.length < 2 || seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 16);
}

// The list page builds on what its article links and on what every repository it lists brings.
const listArticle = (lang) => tl(glossary, 'derive_work_list_article', lang, { periods: listing(periods.map(String), lang), max: periods.at(-1) });
const listTerms = [...new Set([...linkedTerms(listArticle(languages()[0])), ...REPOSITORY_TERMS])];
const nRecent = recent.repos.length - recent.archive;
const since = Math.min(...recent.repos.map(firstYear));

const wanted = new Map();
for (const lang of languages()) {
  const n = recent.repos.length;
  wanted.set(`_index${suffix(lang)}.md`, `+++
${MARK}
title = ${q(t('derive_work_title', lang))}
description = ${q(t('derive_work_list_description', lang, { n, recent: nRecent, max: periods.at(-1), since }))}
template = "work-list.html"
sort_by = "weight"

[extra]
seo_title = ${q(t('derive_work_list_seo_title', lang, { n, author: me.nameIn(lang), since }))}
og_title = ${q(t('derive_work_list_og', lang, { n, recent: nRecent, span: span(lang), since }))}
og_image = ${q(`og/${ogPrefix(lang)}work.png`)}
schema = "collection"
terms = [${listTerms.map(q).join(', ')}]
keywords = [${[t('derive_work_list_keyword', lang, { author: me.nameIn(lang) }), me.github, ...recent.repos.slice(0, 8).map((r) => r.name)].map(q).join(', ')}]
${vizBlock({ kind: 'pulse', source: 'work.all', title: 'viz_work_pulse_title', lead: 'viz_work_pulse_lead', vars: { span: span(lang), cadence: cadenceIn(lang) } })}+++
${listArticle(lang)}
`);
  recent.repos.forEach((r, position) => {
    const curated = curatedOf(r);
    const title = curated?.name ?? r.name;
    wanted.set(`${slug(r.name)}${suffix(lang)}.md`, `+++
${MARK}
title = ${q(title)}
description = ${q(describe(r, lang))}
template = "work.html"
weight = ${position + 1}
updated = ${q(new Date(lastAt(r)).toISOString().replace(/\.\d+Z$/, 'Z'))}

[taxonomies]
tags = [${tags(r, lang).map(q).join(', ')}]

[extra]
repo = ${q(r.name)}
seo_title = ${q(seoTitle(r, lang))}
og_title = ${q(ogTitle(r, lang))}
og_description = ${q(ogDescription(r, lang))}
og_image = ${q(`og/${ogPrefix(lang)}work-${slug(r.name)}.png`)}
schema = "project"
keywords = [${keywords(r, lang).map(q).join(', ')}]
terms = [${termsForRepo(glossary, r, curated, DOSSIER_STACKS.get(r.name) ?? []).map(q).join(', ')}]
${r.commits.length ? vizBlock({
    kind: 'pulse', source: 'work.commits', title: 'viz_commits_title', lead: r.hosts.github ? 'viz_commits_lead_live' : 'viz_commits_lead_snapshot',
    vars: r.hosts.github ? null : { cadence: cadenceIn(lang) },
  }) : ''}+++
${article(r, curated, lang)}
`);
  });
}

const files = writeOrCheck(wanted, { dir: DIR, mark: MARK, label: 'work', orphanWhy: 'has no original repository any more' });
console.log(`work: ${(files - languages().length) / languages().length} project pages (${nRecent} recent, ${recent.archive} archive) and the list, in ${languages().join(', ')}`);
