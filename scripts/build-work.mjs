#!/usr/bin/env node
// Derives one Zola page per repository with a commit in the recent window, content/work/<slug>.md
// in every language, and the list page, from data/recent.json: title, description, SEO and OG front
// matter and the article. The page itself (templates/work.html) renders everything else from the
// data. Nothing here is written by hand; the prose is i18n/derive.toml.
//
// usage: node scripts/build-work.mjs           write them (and remove stale ones)
//        node scripts/build-work.mjs --check   exit 1 if any is missing, stale or orphaned
import { join } from 'node:path';
import {
  ROOT, clip, identity, isDefault, languages, limits, local, ogPrefix, q, readJson, readToml, slug, suffix, t, writeOrCheck,
} from './lib/derive.mjs';
import { listing, loadGlossary, mdEscape, nameLink, onGithubPages, termsForRepo, tl } from './lib/terms.mjs';
import { vizBlock } from './lib/viz.mjs';

const DIR = join(ROOT, 'content/work');
const MARK = '# generated by scripts/build-work.mjs from data/recent.json; do not edit';
const catalogue = readToml('data/projects.toml');
const recent = readJson('data/recent.json');
const glossary = loadGlossary(ROOT);
const me = identity();
const LIMITS = limits();
const periods = recent.periods.map((p) => p.months);
const curatedOf = (r) => catalogue.projects.find((p) => p.repo === r.name);
const categoryName = (r, lang) => local(catalogue.categories[r.category], 'name', lang);

// Deterministic on every machine: UTC and the month names of i18n (locale data and time zones
// differ between this Mac and CI, and a generated file must come out byte-identical everywhere).
const months = (lang) => t('derive_months', lang).split(',');
const date = (iso, lang) => { const d = new Date(iso); return t('derive_date', lang, { day: d.getUTCDate(), month: months(lang)[d.getUTCMonth()], year: d.getUTCFullYear() }); };
const monthYear = (iso, lang) => { const d = new Date(iso); return `${months(lang)[d.getUTCMonth()]} ${d.getUTCFullYear()}`; };
const share = (n, lang) => new Intl.NumberFormat(lang, { maximumFractionDigits: 1, useGrouping: false }).format(n);

// A description within the schema's limits. In the default language from the repository's own
// words (tagline, description, else README); in another language the curated summary there, or a
// sentence derived from the data (category, language, last commit), never machine-translated prose.
function describe(r, lang) {
  const { min, max } = LIMITS.description;
  const curated = curatedOf(r);
  if (!isDefault(lang)) {
    const summary = local(curated, 'summary', lang);
    if (summary && summary.length >= min) return clip(summary, max);
    const language = r.languages[0]?.name ?? r.language;
    return t('derive_work_description', lang, {
      name: curated?.name ?? r.name,
      category: categoryName(r, lang),
      language: language ? t('derive_work_description_language', lang, { language }) : '',
      last: date(r.last_commit, lang),
    });
  }
  const words = [curated?.tagline, r.description, r.readme].filter(Boolean).map((x) => x.replace(/\s+/g, ' ').trim());
  const text = words.find((x) => x.length >= min)
    ?? t('derive_work_description_fallback', lang, { text: words[0] ?? r.name, period: r.period, category: categoryName(r, lang).toLowerCase() });
  return clip(text, max, { min, pad: t('derive_work_description_pad', lang, { author: me.nameIn(lang), period: r.period }) });
}

// The article of a work page, derived from the measured data: what it is, what it is written in,
// when it began and last moved, what it is built with, where it runs, and how to read the page.
// Every term links to the glossary (Zola checks the links); the commit message stays verbatim.
function article(r, curated, lang) {
  const title = `**${mdEscape(curated?.name ?? r.name)}**`;
  const category = `[${categoryName(r, lang)}](@/projects/${r.category}${suffix(lang)}.md)`;
  const langs = r.languages.slice(0, 4);
  const p = [];
  if (langs.length) {
    const main = `${nameLink(glossary, langs[0].name, lang)} (${share(langs[0].share, lang)} %)`;
    const rest = listing(langs.slice(1).map((l) => nameLink(glossary, l.name, lang)), lang);
    p.push(t('derive_work_intro_languages', lang, { title, category, main, rest: rest ? t('derive_work_intro_rest', lang, { list: rest }) : '' }));
  } else {
    p.push(t('derive_work_intro', lang, { title, category }));
  }
  const message = r.last_message ? t('derive_work_message', lang, { message: mdEscape(r.last_message) }) : '';
  p.push(tl(glossary, 'derive_work_history', lang, {
    created: date(r.created_at, lang), created_month: monthYear(r.created_at, lang), last: date(r.last_commit, lang), message, period: r.period,
  }));
  const stack = (curated?.stack ?? []).filter((n) => glossary.byName.has(n.toLowerCase()) && !langs.some((l) => l.name === n));
  if (stack.length) p.push(t('derive_work_stack', lang, { list: listing(stack.map((n) => nameLink(glossary, n, lang)), lang) }));
  if (r.site) {
    p.push(t('derive_work_site', lang, { site: r.site, pages: onGithubPages(r.site) ? tl(glossary, 'derive_work_site_pages', lang) : '' }));
  }
  p.push(t('derive_work_how', lang, {
    latest: t('derive_work_latest_commits', lang, { n: r.commits.length }),
    refresh: t(r.hosts.github ? 'derive_work_refresh_live' : 'derive_work_refresh_snapshot', lang),
    glossary: `@/glossary/_index${suffix(lang)}.md`,
  }));
  return p.join('\n\n');
}

const tags = (r, lang) => [categoryName(r, lang), ...r.languages.slice(0, 3).map((l) => l.name)];

const wanted = new Map();
for (const lang of languages()) {
  const n = recent.repos.length;
  wanted.set(`_index${suffix(lang)}.md`, `+++
${MARK}
title = ${q(t('derive_work_title', lang))}
description = ${q(t('derive_work_list_description', lang, { n, max: periods.at(-1), periods: periods.join(', ') }))}
template = "work-list.html"
sort_by = "weight"

[extra]
og_title = ${q(t('derive_work_list_og', lang, { n }))}
og_image = ${q(`og/${ogPrefix(lang)}work.png`)}
schema = "collection"
terms = ["repository", "commit", "open-source", "data-visualisation"]
keywords = [${[t('derive_work_list_keyword', lang), me.github, ...recent.repos.slice(0, 8).map((r) => r.name)].map(q).join(', ')}]
${vizBlock({ kind: 'pulse', source: 'work.all', title: 'viz_work_pulse_title', lead: 'viz_work_pulse_lead' })}+++
${tl(glossary, 'derive_work_list_article', lang, { periods: listing(periods.map(String), lang) })}
`);
  recent.repos.forEach((r, position) => {
    const curated = curatedOf(r);
    const title = curated?.name ?? r.name;
    const tagline = local(curated, 'tagline', lang) ?? (isDefault(lang) ? r.description : null) ?? categoryName(r, lang);
    wanted.set(`${slug(r.name)}${suffix(lang)}.md`, `+++
${MARK}
title = ${q(title)}
description = ${q(describe(r, lang))}
template = "work.html"
weight = ${position + 1}
updated = ${q(new Date(r.last_commit).toISOString().replace(/\.\d+Z$/, 'Z'))}

[taxonomies]
tags = [${tags(r, lang).map(q).join(', ')}]

[extra]
repo = ${q(r.name)}
og_title = ${q(`${title}: ${tagline}`.slice(0, LIMITS.ogTitle.max))}
og_image = ${q(`og/${ogPrefix(lang)}work-${slug(r.name)}.png`)}
schema = "project"
keywords = [${[title, ...tags(r, lang), me.nameIn(lang)].map(q).join(', ')}]
terms = [${termsForRepo(glossary, r, curated).map(q).join(', ')}]
${r.commits.length ? vizBlock({ kind: 'pulse', source: 'work.commits', title: 'viz_commits_title', lead: r.hosts.github ? 'viz_commits_lead_live' : 'viz_commits_lead_snapshot' }) : ''}+++
${article(r, curated, lang)}
`);
  });
}

const files = writeOrCheck(wanted, { dir: DIR, mark: MARK, label: 'work', orphanWhy: 'has no recent repository any more' });
console.log(`work: ${(files - languages().length) / languages().length} project pages and the list, in ${languages().join(', ')}`);
